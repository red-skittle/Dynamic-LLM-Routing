"""
inference/result.py
-------------------
Standard container returned by every InferenceBackend.

Fields
------
model_id   : Canonical identifier of the model that produced the response.
prompt     : The exact prompt that was sent to the backend.
response   : Text generated by the model (or mock).
elapsed_ms : Wall-clock milliseconds measured *inside the backend call*.
             For the MockBackend this reflects mock overhead only,
             not real LLM inference latency.
timestamp  : UTC datetime when the result was created.
backend    : Name of the backend that produced this result (e.g. "mock").
is_cached  : True when this result was returned from a cache layer.
metadata   : Optional free-form dict for backend-specific extra fields.
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any


@dataclass
class InferenceResult:
    """Immutable record of one inference call."""

    model_id: str
    prompt: str
    response: str
    elapsed_ms: float
    timestamp: datetime
    backend: str
    is_cached: bool = False
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.elapsed_ms < 0:
            raise ValueError(f"elapsed_ms must be non-negative, got {self.elapsed_ms}")
        if not self.model_id:
            raise ValueError("model_id must not be empty")
        if not self.backend:
            raise ValueError("backend must not be empty")
